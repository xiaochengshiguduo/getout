#!/usr/bin/env bash
set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
SCRIPT="$ROOT_DIR/getout.sh"
TMP_ROOT="$(mktemp -d)"
trap 'rm -rf "$TMP_ROOT"' EXIT

pass() { printf '[OK] %s\n' "$*"; }

make_lib() {
  local lib="$1"
  awk '/^main "\$@"/ {exit} {print}' "$SCRIPT" > "$lib"
}

run_build_output_is_current() {
  local before_script="$TMP_ROOT/getout.before" before_hash="$TMP_ROOT/getout.sha256.before"
  cp "$ROOT_DIR/getout.sh" "$before_script"
  cp "$ROOT_DIR/getout.sh.sha256" "$before_hash"
  "$ROOT_DIR/build.sh" >/dev/null
  cmp -s "$before_script" "$ROOT_DIR/getout.sh"
  cmp -s "$before_hash" "$ROOT_DIR/getout.sh.sha256"
  grep -q 'Generated by build.sh from src/\*.sh' "$ROOT_DIR/getout.sh"
  pass 'build.sh output is current and marked generated'
}

run_bash_syntax() {
  bash -n "$SCRIPT"
  pass 'getout.sh syntax'
}

run_route_script_syntax() {
  local t="$TMP_ROOT/routes"
  local lib="$t/lib.sh"
  mkdir -p "$t"
  make_lib "$lib"
  (
    set -euo pipefail
    # shellcheck disable=SC1090
    . "$lib"
    CONF_DIR="$t/conf"
    CLIENT_CONF="$CONF_DIR/client.conf"
    ROUTES_UP="$CONF_DIR/routes-up.sh"
    ROUTES_DOWN="$CONF_DIR/routes-down.sh"
    mkdir -p "$CONF_DIR"
    write_routes_scripts
    bash -n "$ROUTES_UP"
    bash -n "$ROUTES_DOWN"
    grep -q '^ensure_nftables()' "$ROUTES_UP"
    ! grep -q 'apt-get' "$ROUTES_UP"
  )
  pass 'generated route scripts syntax'
}

run_runtime_restore_deletes_new_files() {
  local t="$TMP_ROOT/runtime"
  local lib="$t/lib.sh"
  mkdir -p "$t"
  make_lib "$lib"
  (
    set -euo pipefail
    # shellcheck disable=SC1090
    . "$lib"
    CONF_DIR="$t/etc-getout"
    CLIENT_CONF="$CONF_DIR/client.conf"
    TUN_CONF="$CONF_DIR/tun2socks.yaml"
    WG_CONF="$CONF_DIR/getout-wg0.conf"
    ROUTES_UP="$CONF_DIR/routes-up.sh"
    ROUTES_DOWN="$CONF_DIR/routes-down.sh"
    TUN_SERVICE="$t/getout-tun.service"
    WG_SERVICE="$t/getout-wg.service"
    MODE_FILE="$CONF_DIR/mode"
    systemctl() { :; }
    mkdir -p "$CONF_DIR"
    printf 'old-client\n' > "$CLIENT_CONF"
    printf 'old-routes-up\n' > "$ROUTES_UP"
    printf 'old-wg-conf\n' > "$WG_CONF"
    printf 'old-wg-service\n' > "$WG_SERVICE"
    snapshot="$(snapshot_runtime_files)"
    begin_runtime_rollback "$snapshot"
    printf 'new-client\n' > "$CLIENT_CONF"
    printf 'new-tun\n' > "$TUN_CONF"
    printf 'new-routes-up\n' > "$ROUTES_UP"
    printf 'new-routes-down\n' > "$ROUTES_DOWN"
    printf 'new-service\n' > "$TUN_SERVICE"
    printf 'new-wg-conf\n' > "$WG_CONF"
    printf 'new-wg-service\n' > "$WG_SERVICE"
    printf 'dual\n' > "$MODE_FILE"
    restore_runtime_or_warn "$snapshot" >/dev/null 2>&1
    [ "$(cat "$CLIENT_CONF")" = old-client ]
    [ "$(cat "$ROUTES_UP")" = old-routes-up ]
    [ "$(cat "$WG_CONF")" = old-wg-conf ]
    [ "$(cat "$WG_SERVICE")" = old-wg-service ]
    [ ! -e "$TUN_CONF" ]
    [ ! -e "$ROUTES_DOWN" ]
    [ ! -e "$TUN_SERVICE" ]
    [ ! -e "$MODE_FILE" ]
  )
  pass 'runtime rollback restores old files and deletes new files'
}

run_preflight_failure_rolls_back() {
  local t="$TMP_ROOT/preflight"
  local lib="$t/lib.sh"
  mkdir -p "$t"
  make_lib "$lib"
  cat > "$t/case.sh" <<'CASE'
#!/usr/bin/env bash
set -euo pipefail
. "$1"
root="$2"
CONF_DIR="$root/etc-getout"
CLIENT_CONF="$CONF_DIR/client.conf"
TUN_CONF="$CONF_DIR/tun2socks.yaml"
ROUTES_UP="$CONF_DIR/routes-up.sh"
ROUTES_DOWN="$CONF_DIR/routes-down.sh"
TUN_SERVICE="$root/getout-tun.service"
MODE_FILE="$CONF_DIR/mode"
TUN_BIN="$root/missing-tun2socks"
systemctl() { :; }
mkdir -p "$CONF_DIR"
printf 'old-client\n' > "$CLIENT_CONF"
snapshot="$(snapshot_runtime_files)"
begin_runtime_rollback "$snapshot"
printf '%s\n' "$snapshot" > "$root/snapshot-path"
printf 'new-client\n' > "$CLIENT_CONF"
printf 'new-tun\n' > "$TUN_CONF"
