  [ ! -e "$t/root/etc-getout/tun2socks.yaml" ]
  snapshot="$(cat "$t/root/snapshot-path")"
  [ ! -d "$snapshot" ]
  grep -q '未找到可执行 tun2socks' <<<"$out"
  pass 'preflight failure rolls back runtime snapshot'
}

