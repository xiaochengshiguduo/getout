run_menu_order_matches_readme() {
  local status_line restart_line update_line uninstall_line exit_line
  status_line="$(grep -n '查看状态' "$SCRIPT" | grep 'echo' | head -n1 | cut -d: -f1)"
  restart_line="$(grep -n '重启 getout' "$SCRIPT" | grep 'echo' | head -n1 | cut -d: -f1)"
  update_line="$(grep -n '更新 getout' "$SCRIPT" | grep 'echo' | head -n1 | cut -d: -f1)"
  uninstall_line="$(grep -n '卸载 getout' "$SCRIPT" | grep 'echo' | head -n1 | cut -d: -f1)"
  exit_line="$(grep -n '退出' "$SCRIPT" | grep 'echo' | grep -v '已取消' | head -n1 | cut -d: -f1)"
  [ -n "$status_line" ] && [ -n "$restart_line" ] && [ -n "$update_line" ] && [ -n "$uninstall_line" ] && [ -n "$exit_line" ]
  [ "$status_line" -lt "$restart_line" ] && [ "$restart_line" -lt "$update_line" ] && [ "$update_line" -lt "$uninstall_line" ] && [ "$uninstall_line" -lt "$exit_line" ]
  grep -q '请选择 \[1-' "$SCRIPT"
  grep -q '请选择 \[1/2\]' "$SCRIPT"
  grep -q 'echo "  1\. SOCKS5 模式"' "$SCRIPT"
  grep -q 'echo "  2\. WireGuard 模式"' "$SCRIPT"
  ! grep -q '请选择 \[a/b\]' "$SCRIPT"
  ! grep -q 'echo "9\.环境诊断"' "$SCRIPT"
  pass 'menu order matches documented release menu'
}

run_checksum_file_matches_script() {
  [ -f "$ROOT_DIR/getout.sh.sha256" ]
  (cd "$ROOT_DIR" && sha256sum -c getout.sh.sha256 >/dev/null)
  pass 'repository getout.sh.sha256 matches getout.sh'
}

run_checksum_verification() {
  local t="$TMP_ROOT/checksum"
  local lib="$t/lib.sh" sample="$t/sample.sh"
  mkdir -p "$t"
  make_lib "$lib"
  printf 'hello\n' > "$sample"
  (
    set -euo pipefail
    # shellcheck disable=SC1090
    . "$lib"
    GETOUT_UPDATE_SHA256="$(sha256sum "$sample" | awk '{print $1}')"
    verify_update_checksum "$sample"
  )
  set +e
  out="$(bash -c '. "$1"; GETOUT_UPDATE_SHA256=bad verify_update_checksum "$2"' _ "$lib" "$sample" 2>&1)"
  rc=$?
  set -e
  [ "$rc" -ne 0 ]
  grep -q 'SHA256 校验失败' <<<"$out"
  pass 'update checksum verification accepts match and rejects mismatch'
}


